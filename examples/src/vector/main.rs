use dapr::client::{
    DistanceMetric, IndexingOptionsAlpha1, IndexingWaitTimeoutAction, QueryVectorsRequestBuilder,
    VectorRecord, batch_query_result_alpha1, json_to_struct,
};
use serde_json::json;
use std::time::Duration;

const STORE_NAME: &str = "vectors";
const COLLECTION: &str = "cars";

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Sleep to allow for the server to become available
    tokio::time::sleep(Duration::from_secs(5)).await;

    // Connect using env vars
    let mut client = dapr::Client::new().await?;

    // Embeddings are generated by the application. This example uses 3 dimensions.
    client
        .create_collection_alpha1(STORE_NAME, COLLECTION, 3, DistanceMetric::Cosine, None)
        .await?;
    println!("collection created: {COLLECTION}");

    let records = vec![
        VectorRecord::new("roadster", vec![0.9, 0.1, 0.0])
            .with_metadata(json_to_struct(json!({"category": "sports"}))?),
        VectorRecord::new("hatchback", vec![0.7, 0.3, 0.0])
            .with_metadata(json_to_struct(json!({"category": "compact"}))?),
        VectorRecord::new("pickup", vec![0.0, 0.2, 0.9])
            .with_metadata(json_to_struct(json!({"category": "truck"}))?)
            .with_payload(b"towing capacity 5t".to_vec()),
    ];

    // Wait for the records to be indexed so they are immediately queryable
    let options = IndexingOptionsAlpha1::wait_for_completion(
        Duration::from_secs(10),
        IndexingWaitTimeoutAction::FailRequest,
    );
    let response = client
        .upsert_vectors_alpha1(STORE_NAME, COLLECTION, records, Some(options), None)
        .await?;
    println!(
        "upserted vectors: ack={:?} failed={}",
        response.ack(),
        response.failed_items.len()
    );

    let query = QueryVectorsRequestBuilder::vector(vec![1.0, 0.0, 0.0])
        .with_top_k(2)
        .build();
    let response = client
        .query_vectors_alpha1(STORE_NAME, COLLECTION, query)
        .await?;
    for m in response.matches {
        if let Some(record) = m.record {
            println!("query match: {} score={:.3}", record.id, m.score);
        }
    }

    // Each query in a batch succeeds or fails on its own
    let queries = vec![
        QueryVectorsRequestBuilder::by_id("pickup")
            .with_top_k(1)
            .build(),
        QueryVectorsRequestBuilder::vector(vec![0.5, 0.5, 0.0])
            .with_filter(json_to_struct(json!({"category": {"$eq": "compact"}}))?)
            .with_top_k(1)
            .build(),
    ];
    let response = client
        .batch_query_vectors_alpha1(STORE_NAME, COLLECTION, queries, None)
        .await?;
    for (i, result) in response.results.into_iter().enumerate() {
        match result.result {
            Some(batch_query_result_alpha1::Result::Response(response)) => {
                for m in response.matches {
                    if let Some(record) = m.record {
                        println!("batch query {i} match: {}", record.id);
                    }
                }
            }
            Some(batch_query_result_alpha1::Result::Error(status)) => {
                println!("batch query {i} failed: {}", status.message);
            }
            None => {}
        }
    }

    let response = client
        .get_vectors_alpha1(STORE_NAME, COLLECTION, ["pickup"], true, None)
        .await?;
    for record in response.records {
        println!(
            "got vector: {} values={:?} payload={}",
            record.id,
            record.values,
            String::from_utf8_lossy(&record.payload)
        );
    }

    client
        .delete_vectors_alpha1(
            STORE_NAME,
            COLLECTION,
            ["roadster", "hatchback", "pickup"],
            None,
            None,
        )
        .await?;
    client
        .delete_collection_alpha1(STORE_NAME, COLLECTION, None)
        .await?;
    println!("collection deleted: {COLLECTION}");

    Ok(())
}
